library(testthat)

scrub_environment_code <- function(x) {
  # macos: 9
  # linux: 12
  # windows: 16
  m <- regexpr("(?<=<environment: 0x)[0-9a-f]+(?=>)", x, perl = TRUE)
  regmatches(x, m) <- strrep("0", max(0, 12L))
  x
}

test_documentation <- function() {
  skip_if_not_installed("here")

  cwd <- setwd(here::here())
  on.exit(setwd(cwd))

  dir <- tempfile("cnd_dir_")
  on.exit(unlink(dir, TRUE), add = TRUE)
  dir.create(dir, showWarnings = FALSE)
  # path to where the documentation will be sent
  path <- tempfile("cnd_documentation_", dir, ".R")

  # extra file to trigger cleanup
  temp <- tempfile("cnd_auto_generated_", dir, ".R")
  writeLines("# % Generated by cnd: do not edit by hand", temp)

  suppress_cnd_conditions(
    expect_message(
      expect_condition(
        expect_identical(cnd_document(package = "cnd", file = path), path),
        class = "cnd::cnd_generated_write"
      ),
      class = "cnd::cnd_generated_cleanup"
    )
  )

  # no changes
  expect_no_condition(cnd_document(package = "cnd", file = path))

  skip_if_not_installed("roxygen2")
  parsed <- roxygen2::parse_text(readLines(path)[-1:-2], test_env())
  expect_failure(expect_identical(parsed, list()))
}

local_registry <- function(name = basename(tempfile(""))) {
  registrar$add(name)
  do <- as.call(list(function() registrar$remove(name)))
  do.call(on.exit, list(do), envir = parent.frame())
  registrar$get(name)
}

# from RConsortium/S7 tests

quick_install <- function(package, lib, quiet = TRUE) {
  opts <- c(
    "--data-compress=none",
    "--no-byte-compile",
    "--no-data",
    "--no-demo",
    "--no-docs",
    "--no-help",
    "--no-html",
    "--no-libs",
    "--use-vanilla",
    NULL
  )

  for (p in package) {
    utils::install.packages(
      pkgs = p,
      lib = lib,
      repos = NULL,
      type = "source",
      quiet = quiet,
      INSTALL_opts = paste(opts, collapse = " ")
    )
  }
}

local_install_and_attach <- function(path, lib, frame = parent.frame()) {
  quick_install(path, lib)
  package <- basename(path)
  library(package, character.only = TRUE)
  defer(
    try(detach(paste0("package:", package), unload = TRUE), silent = TRUE),
    frame = frame
  )
  invisible(package)
}

# Lightweight equivalent of withr::defer()
defer <- function(expr, frame = parent.frame(), after = FALSE) {
  thunk <- as.call(list(function() expr))
  do.call(on.exit, list(thunk, TRUE, after), envir = frame)
}
